// Offline companion to lib-canopy.py. Existing optimizer supplies meshopt + KTX2.
import { readFile, writeFile, stat } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { createIO, statistics } from '../shared.mjs';
process.env.PATH = `C:/Program Files/KTX-Software/bin;${process.env.PATH}`;
const io = await createIO();
const manifest = JSON.parse(await readFile('public/world/lib/manifest.json', 'utf8'));
for (const asset of manifest.assets.filter(a => a.id.startsWith('tree-broadleaf-'))) {
  for (const lod of asset.lods) {
    const input = `tmp/p3-library/${lod.file}`;
    const doc = await io.read(input);
    for (const mesh of doc.getRoot().listMeshes()) for (const primitive of mesh.listPrimitives()) {
      if (primitive.getMaterial()?.getAlphaMode() === 'OPAQUE') continue;
      const position = primitive.getAttribute('POSITION');
      const colors = new Float32Array(position.getCount() * 3), point = [];
      for (let i = 0; i < position.getCount(); i++) {
        position.getElement(i, point);
        const ao = .68 + .32 * Math.max(0, Math.min(1, point[1] / 9));
        colors.set([.12 * ao, .26 * ao, .075 * ao], i * 3);
      }
      // Blender's exporter can omit COLOR_0 on image/vertex multiply graphs.
      primitive.setAttribute('COLOR_0', doc.createAccessor().setType('VEC3').setArray(colors).setBuffer(position.getBuffer()));
    }
    for (const material of doc.getRoot().listMaterials()) {
      if (material.getAlphaMode() !== 'OPAQUE') material.setAlphaMode('MASK').setAlphaCutoff(.45).setDoubleSided(true);
    }
    await io.write(input, doc);
    const result = spawnSync(process.execPath, ['tools/assets/optimize.mjs', input, `public/world/lib/${lod.file}`], { encoding: 'utf8', windowsHide: true });
    if (result.status !== 0) throw new Error(result.stderr || result.stdout);
    const optimized = await io.read(`public/world/lib/${lod.file}`);
    Object.assign(lod, statistics(optimized), { bytes: (await stat(`public/world/lib/${lod.file}`)).size });
    console.log(lod.file, lod.triangles, 'tri', lod.bytes, 'bytes');
  }
  asset.derivation = 'GFX-P3 refinement of GFX-02 original: rounded folded alpha-cutout leaves around layered canopy cores; deterministic intact-card LOD1. tools/assets/blender/lib-canopy.py; CC0-1.0';
}
manifest.note = 'GFX-02 CC0 library, integrated by foliage/library.ts after play. Broadleaf refinement by GFX-P3; three variants per species, intact-card LODs; runtime four-view impostors.';
manifest.textureMaxDimension = 256;
await writeFile('public/world/lib/manifest.json', JSON.stringify(manifest, null, 2) + '\n');
// Public paths are unchanged. Correct the six existing license rows to match the
// original CC0 derivative and its new atlas/material metrics; no new public file.
let licenses = await readFile('assets/LICENSES.csv', 'utf8');
for (const asset of manifest.assets.filter(a => a.id.startsWith('tree-broadleaf-'))) for (const lod of asset.lods) {
  const prefix = `public/world/lib/${lod.file},`;
  licenses = licenses.split('\n').map(line => line.startsWith(prefix)
    ? `${prefix}Codex A (project-original),CC0-1.0,yes,yes,yes,none,Generated by tools/assets/blender/lib-canopy.py,256x256 KTX2,${lod.materials},LOD${lod.level},none`
    : line).join('\n');
}
await writeFile('assets/LICENSES.csv', licenses);
