// GFX-02 companion to lib-build.py. Uses installed tooling; no downloads.
import { readFile, writeFile, mkdir, readdir, stat, appendFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { chromium } from '@playwright/test';
import { createServer } from 'vite';
import { createRequire } from 'node:module';
import { createIO, statistics } from '../shared.mjs';

const require = createRequire(import.meta.url);
const sharp = require(require.resolve('sharp', { paths: [require.resolve('next/package.json')] }));
const directory = 'public/world/lib';
await mkdir(directory, { recursive: true });
const entries = JSON.parse(await readFile('tmp/lib-export/inventory.json', 'utf8'));
const io = await createIO();
const csv = await readFile('assets/LICENSES.csv', 'utf8');
const additions = [];
const rows = [];
for (const entry of entries) {
  entry.derivation = entry.id.startsWith('tree-pine')
    ? 'Whole Poly Haven needle-sprig alpha cards in overlapping conical whorls; warm rebuilt trunk'
    : entry.id.startsWith('rock-') ? 'Decimated boulder; scaled and sheared variants of one source'
      : entry.source[0].startsWith('project-original') ? 'Deterministic project-original geometry; dedicated to CC0'
        : 'Decimated Poly Haven mesh';
  for (const lod of entry.lods) {
    const target = `${directory}/${lod.file}`;
    const keepApproved = /^(rock-|prop-fern$|prop-fallen-log$)/.test(entry.id);
    if (!keepApproved) {
      const prepared = await io.read(`tmp/lib-export/${lod.file}`);
      for (const material of prepared.getRoot().listMaterials()) {
        if (material.getAlphaMode() !== 'OPAQUE') material.setAlphaMode('MASK').setAlphaCutoff(.5).setDoubleSided(true);
      }
      await io.write(`tmp/lib-export/prepared-${lod.file}`, prepared);
      const result = spawnSync(process.execPath, ['tools/assets/optimize.mjs', `tmp/lib-export/prepared-${lod.file}`, target], {
        encoding: 'utf8', windowsHide: true,
      });
      if (result.status !== 0) throw new Error(result.stderr || result.stdout);
    }
    const document = await io.read(target);
    const metrics = statistics(document);
    const root = document.getRoot();
    if (root.listScenes().length !== 1 || root.listNodes().length !== 1) throw new Error(`Unexpected objects: ${target}`);
    for (const texture of root.listTextures()) {
      const bytes = texture.getImage();
      if (texture.getMimeType() !== 'image/ktx2') throw new Error(`Not KTX2: ${target}`);
      const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
      if (view.getUint32(20, true) > 1024 || view.getUint32(24, true) > 1024) throw new Error(`Texture >1K: ${target}`);
    }
    Object.assign(lod, metrics, { path: `/world/lib/${lod.file}`, bytes: (await stat(target)).size });
    if (lod.triangles > (lod.level ? 2000 : 8000)) throw new Error(`LOD budget: ${target}`);
    const creator = entry.source.some(s => s.startsWith('https://polyhaven')) ? 'Poly Haven / Codex A derivative' : 'Codex A (project-original)';
    const fields = [target, creator, 'CC0-1.0', 'yes', 'yes', 'yes', 'none', entry.source.join('; '), metrics.textures ? (entry.category === 'rock' ? '64x64 KTX2' : '128x128 KTX2') : '-', metrics.materials, `LOD${lod.level}`, 'none'];
    if (!csv.includes(`${target},`)) additions.push(fields.join(','));
  }
  rows.push(`| ${entry.id} | ${entry.lods.map(l => l.triangles).join(' / ')} | ${entry.lods.map(l => l.bytes).join(' / ')} |`);
  console.log(entry.id, entry.lods.map(l => `${l.triangles}tri/${l.bytes}B`).join(' '));
}
const raw = await readFile('tmp/raw-polyhaven/batch1_pine_boulder_fern.blend');
const manifest = {
  version: 1, units: 'metres', upAxis: 'Y', origin: 'base centered',
  compression: ['EXT_meshopt_compression', 'KHR_texture_basisu'],
  textureMaxDimension: 128,
  sourceBlendSha256: createHash('sha256').update(raw).digest('hex'),
  note: 'Offline styleframe library. Select one LOD per asset. No runtime integration. Rock variants share one source; pine whole-sprig cards arranged in dense conical tiers. CC0 applies to original additions too.',
  assets: entries,
};
await writeFile(`${directory}/manifest.json`, JSON.stringify(manifest, null, 2) + '\n');
if (!csv.includes(`${directory}/manifest.json,`)) additions.push(`${directory}/manifest.json,Codex A (project-original),CC0-1.0,yes,yes,yes,none,Generated by tools/assets/blender/lib-package.mjs,-,-,-,none`);
if (additions.length) await appendFile('assets/LICENSES.csv', (csv.endsWith('\n') ? '' : '\n') + additions.join('\n') + '\n');
await mkdir('docs/showcase/37-aaa', { recursive: true });
await writeFile('tmp/lib-export/table.md', '| Asset | Tri LOD0 / LOD1 | Byte LOD0 / LOD1 |\n|---|---:|---:|\n' + rows.join('\n') + '\n');
console.log('Total GLB bytes:', entries.flatMap(a => a.lods).reduce((sum, l) => sum + l.bytes, 0));
console.log('Public files:', (await readdir(directory)).length);

