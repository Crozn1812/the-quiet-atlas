"""Bake deterministic hemisphere-ray AO into original linear vertex pigments, then export.

Geometry is generated by the in-repo rock/wood factories through props.mjs.
No images or external models. AO includes a temporary contact plane, never exported.
"""
import json
import math
import os
import sys
import bpy
from mathutils import Vector
from mathutils.bvhtree import BVHTree


def bake(source, directory):
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    values = source["positions"]
    # Three Y-up -> Blender Z-up; exporter restores Three coordinates.
    vertices = [(values[i], -values[i + 2], values[i + 1]) for i in range(0, len(values), 3)]
    faces = [tuple(range(i, i + 3)) for i in range(0, len(vertices), 3)]
    assert len(faces) <= source["limit"]
    mesh = bpy.data.meshes.new(source["name"])
    mesh.from_pydata(vertices, [], faces)
    mesh.update()
    obj = bpy.data.objects.new(source["name"], mesh)
    bpy.context.collection.objects.link(obj)
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    ground = min(v[2] for v in vertices)
    n = len(vertices)
    occluder = vertices + [(-50, -50, ground), (50, -50, ground), (50, 50, ground), (-50, 50, ground)]
    tree = BVHTree.FromPolygons(occluder, faces + [(n, n + 1, n + 2, n + 3)])
    color = mesh.color_attributes.new(name="Color", type="FLOAT_COLOR", domain="CORNER")
    samples = 48
    for polygon in mesh.polygons:
        normal = polygon.normal
        tangent = normal.cross(Vector((0, 0, 1)) if abs(normal.z) < 0.9 else Vector((0, 1, 0))).normalized()
        bitangent = normal.cross(tangent)
        for loop in polygon.loop_indices:
            point = mesh.vertices[mesh.loops[loop].vertex_index].co
            # Move away from coincident bevel edges and towards the face centre.
            origin = point.lerp(polygon.center, 0.035) + normal * 0.001
            hits = 0
            for j in range(samples):
                radius = math.sqrt((j + 0.5) / samples)
                angle = j * 2.399963229728653
                direction = tangent * (radius * math.cos(angle)) + bitangent * (radius * math.sin(angle)) + normal * math.sqrt(1 - radius * radius)
                if tree.ray_cast(origin, direction, 0.65)[0] is not None:
                    hits += 1
            ao = 1 - 0.32 * hits / samples
            index = mesh.loops[loop].vertex_index * 3
            color.data[loop].color = (*[v * ao for v in source["colors"][index:index + 3]], 1)
    material = bpy.data.materials.new("palette-vertex-AO")
    material.use_nodes = True
    nodes = material.node_tree.nodes
    shader = nodes.get("Principled BSDF")
    shader.inputs["Roughness"].default_value = 1
    shader.inputs["Metallic"].default_value = 0
    vertex_color = nodes.new("ShaderNodeVertexColor")
    vertex_color.layer_name = "Color"
    material.node_tree.links.new(vertex_color.outputs["Color"], shader.inputs["Base Color"])
    mesh.materials.append(material)
    obj["ao_bake"] = "48 cosine hemisphere rays; 0.65m contact radius; strength 0.32"
    bpy.ops.export_scene.gltf(filepath=os.path.join(directory, source["name"] + ".glb"),
                              export_format="GLB", use_selection=True, export_yup=True,
                              export_extras=True, export_animations=False, export_cameras=False, export_lights=False)


def main(argv):
    source, directory = argv
    os.makedirs(directory, exist_ok=True)
    with open(source, encoding="utf8") as handle:
        for entry in json.load(handle):
            bake(entry, directory)


if __name__ == "__main__":
    main(sys.argv[sys.argv.index("--") + 1:])
